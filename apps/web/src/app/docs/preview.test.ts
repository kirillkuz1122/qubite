import { describe, expect, it } from 'vitest';
import { plainPreview } from './preview';

describe('превью документа без разметки', () => {
  it('убирает знаки блоков: заголовки, списки, чек-лист, цитату', () => {
    expect(
      plainPreview(
        '# Заголовок\nТекст документа\n- [ ] Пункт\n- [x] Готово\n## Раздел\n- раз\n1. два\n> мысль',
      ),
    ).toBe('Заголовок Текст документа Пункт Готово Раздел раз два мысль');
  });

  it('убирает ограду кода и знаки форматирования, но не трогает слова', () => {
    expect(
      plainPreview('```\nfor v in graph:\n```\n**жирный** *курсив* ~~нет~~ `код` snake_case 2 * 3'),
    ).toBe('for v in graph: жирный курсив нет код snake_case 2 * 3');
  });

  it('с отступами вложенных пунктов и экранированием', () => {
    expect(plainPreview('  - вложенный\n    [ ] дело\n\\# не заголовок')).toBe(
      'вложенный дело # не заголовок',
    );
  });

  it('ссылка — только её текст, как у сервера', () => {
    expect(
      plainPreview('# Заголовок\n\n- [ ] **Шаг** [ссылка](https://example.org)\n\n`код`'),
    ).toBe('Заголовок Шаг ссылка код');
  });

  it('пустой документ — пустая строка', () => {
    expect(plainPreview('\n\n  ')).toBe('');
  });
});
