/**
 * Превью в списке документов — чистый текст. Сервер и редактор отдают Markdown
 * («# Заголовок», «- [ ] Пункт», «**жирный**»); разметку убираем только при показе,
 * сохранённый текст не меняется.
 */
const LINE_MARK = /^\s*(?:#{1,6}\s+|>\s?|(?:[-*+]\s+)?\[[ xX]\]\s+|[-*+]\s+|\d+[.)]\s+)/;

export function plainPreview(markdown: string): string {
  return (
    markdown
      .split('\n')
      // ограда блока кода («```») — не текст
      .map((line) => (/^\s*`{3,}/.test(line) ? '' : line.replace(LINE_MARK, '')))
      .join(' ')
      // [текст](адрес) и картинки — только текст
      .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
      .replace(/\*\*|__|~~|`/g, '')
      // одиночные * и _ у краёв слова — курсив; внутри слова (snake_case) остаются
      .replace(/(^|[\s(«"])[*_]+(?=\S)/g, '$1')
      .replace(/(\S)[*_]+(?=$|[\s.,;:!?)»"])/g, '$1')
      .replace(/\\([\\`*_{}[\]()#+\-.!>~|])/g, '$1')
      .replace(/\s+/g, ' ')
      .trim()
  );
}
