export function themeVariables(p: Palette, night: boolean) {
  const keys = [
    "--bg",
    "--surface",
    "--surface2",
    "--text",
    "--muted",
    "--line",
    "--pigment",
    "--ink",
  ];
  const colors = night ? p.dark : p.light;
  return Object.fromEntries([
    ...keys.map((k, i) => [k, colors[i]]),
    ["--accent", "roles" in p ? (night ? "#a8d9ff" : "#235879") : colors[6]],
    ["--on-accent", colors[7]],
    ["--tone-a", p.colors[0]],
    ["--tone-b", p.colors[1]],
    ["--tone-c", p.colors[2]],
    ...("roles" in p
      ? [
          ["--plastic-action", p.roles.action],
          ["--plastic-select", p.roles.select],
          ["--plastic-idea", p.roles.idea],
          ["--plastic-success", p.roles.success],
          ["--plastic-error", p.roles.error],
          ["--plastic-ink", "#18252c"],
        ]
      : []),
  ]);
}
